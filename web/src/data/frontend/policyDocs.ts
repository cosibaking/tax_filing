export function getPolicyDocsByCategory(categoryId: string) {
  return POLICY_DOC_ARTICLES
    .filter((d) => d.categoryId === categoryId)
    .sort((a, b) => b.sort - a.sort)
    .map((d) => ({
      id: d.slug,
      slug: d.slug,
      title: d.title,
      summary: d.summary,
    }))
}

export function getPolicyDocBySlug(slug: string) {
  const article = POLICY_DOC_ARTICLES.find((d) => d.slug === slug)
  if (!article) return null
  const cat = POLICY_DOC_CATEGORIES.find((c) => c.id === article.categoryId)
  return {
    id: article.slug,
    slug: article.slug,
    title: article.title,
    summary: article.summary,
    content: article.content,
    author: '金税管家',
    updatedAt: '2026-06-09',
    views: 0,
    categoryName: cat?.title || '政策与合规科普',
  }
}

export function searchPolicyDocs(keyword: string) {
  const kw = keyword.trim().toLowerCase()
  if (!kw) return []
  return POLICY_DOC_ARTICLES
    .filter((d) => {
      const hay = `${d.title} ${d.summary} ${d.content}`.toLowerCase()
      return hay.includes(kw)
    })
    .map((d) => {
      const cat = POLICY_DOC_CATEGORIES.find((c) => c.id === d.categoryId)
      const matchContent = d.content.toLowerCase().includes(kw)
      return {
        id: d.slug,
        slug: d.slug,
        title: d.title,
        categoryName: cat?.title || '',
        matchType: matchContent ? 'content' : 'title',
      }
    })
}

export function getFirstPolicyDocSlug() {
  const sorted = [...POLICY_DOC_ARTICLES].sort((a, b) => b.sort - a.sort)
  return sorted[0]?.slug || ''
}
